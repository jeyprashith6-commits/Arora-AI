export function getSubjectPyqs(
  subjectId: SubjectId,
  yearFilter: number | 'all' = 'all',
): QuestionItem[] {
  return LAST_6_YEARS_PYQ_ARCHIVE.filter(
    (q) => q.subjectId === subjectId && (yearFilter === 'all' || q.pyqYear === yearFilter),
  ).sort((a, b) => (b.pyqYear ?? 0) - (a.pyqYear ?? 0));
}

export function getGuidesForSubject(subjectId: SubjectId): PaperGenerationGuideProfile[] {
  return PAPER_GENERATION_GUIDES.filter((g) => g.subjects.includes(subjectId));
}

export function getGuideQuestionsForSubject(
  subjectId: SubjectId,
  guideBook: ReferenceBookName | 'all' = 'all',
  extraPool: QuestionItem[] = [],
): QuestionItem[] {
  const combined = [...GUIDE_PRACTICE_QUESTIONS, ...extraPool];
  const seen = new Set<string>();
  return combined.filter((q) => {
    if (seen.has(q.id)) return false;
    seen.add(q.id);
    if (q.subjectId !== subjectId) return false;
    if (guideBook !== 'all' && q.sourceBook !== guideBook) return false;
    return true;
  });
}
